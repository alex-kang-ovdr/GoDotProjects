#!/usr/bin/env node
// Custom-fork Godot web editor binaries for the Cloud Run Forge image.
//
// forge/OfficialGodot/vendor-release/ is gitignored (57 MB WASM), so a CI checkout
// never contains it and the image would ship without the editor
// (/forge/OfficialGodot/vendor/godot.editor.js -> 404). The binaries are kept in
// GCS under <base>/<web-editor expectedForkCommit>/ with a SHA256SUMS manifest:
//
//   publish (developer PC, after tools/forge/build-web-editor-release.ps1):
//     node deploy/cloudrun/forge/web-editor-artifact.mjs publish --base gs://.../forge/web-editor
//   fetch (CI, before docker build; fails closed when missing or tampered):
//     node deploy/cloudrun/forge/web-editor-artifact.mjs fetch --base gs://.../forge/web-editor
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
export const repoRoot = path.resolve(__dirname, '../../..');
export const vendorReleaseDir = path.join(repoRoot, 'forge', 'OfficialGodot', 'vendor-release');
export const MANIFEST_NAME = 'SHA256SUMS';
export const REQUIRED_FILES = ['godot.editor.js', 'godot.editor.wasm'];
// Derived files are regenerated by the Dockerfile prep stage; never publish them.
const DERIVED = /\.(br|gz)$|^wasm-meta\.json$/;

export function webEditorArtifactVersion(ssotPath = path.join(repoRoot, 'tools', 'engine', 'engine-ssot.json')) {
  const ssot = JSON.parse(fs.readFileSync(ssotPath, 'utf8'));
  const commit = ssot?.targets?.['web-editor']?.expectedForkCommit;
  if (!/^[0-9a-f]{40}$/.test(String(commit || ''))) {
    throw new Error('engine-ssot.json targets["web-editor"].expectedForkCommit must be a 40-hex commit');
  }
  return commit;
}

export function sha256File(file) {
  return crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
}

export function listPublishableFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter(e => e.isFile() && !DERIVED.test(e.name) && e.name !== MANIFEST_NAME)
    .map(e => e.name)
    .sort();
}

export function buildManifest(dir) {
  const names = listPublishableFiles(dir);
  for (const required of REQUIRED_FILES) {
    if (!names.includes(required)) throw new Error(`web editor artifact is missing ${required} in ${dir}`);
  }
  return names.map(name => `${sha256File(path.join(dir, name))}  ${name}`).join('\n') + '\n';
}

export function parseManifest(text) {
  const entries = new Map();
  for (const line of String(text).split(/\r?\n/)) {
    if (!line.trim()) continue;
    const m = /^([0-9a-f]{64}) {2}([A-Za-z0-9._-]+)$/.exec(line);
    if (!m) throw new Error(`invalid ${MANIFEST_NAME} line: ${line}`);
    entries.set(m[2], m[1]);
  }
  for (const required of REQUIRED_FILES) {
    if (!entries.has(required)) throw new Error(`${MANIFEST_NAME} does not list ${required}`);
  }
  return entries;
}

export function verifyDir(dir) {
  const entries = parseManifest(fs.readFileSync(path.join(dir, MANIFEST_NAME), 'utf8'));
  for (const [name, expected] of entries) {
    const file = path.join(dir, name);
    if (!fs.existsSync(file)) throw new Error(`web editor artifact file missing after fetch: ${name}`);
    const actual = sha256File(file);
    if (actual !== expected) throw new Error(`web editor artifact checksum mismatch: ${name}`);
  }
  return entries;
}

function gcloud(args) {
  const result = spawnSync('gcloud', args, { stdio: 'inherit', shell: process.platform === 'win32' });
  if (result.status !== 0) throw new Error(`gcloud ${args.slice(0, 3).join(' ')} failed (exit ${result.status})`);
}

function parseArgs(argv) {
  const [command, ...rest] = argv;
  const opts = { command };
  for (let i = 0; i < rest.length; i++) {
    if (rest[i] === '--base') opts.base = rest[++i];
    else if (rest[i] === '--dir') opts.dir = path.resolve(rest[++i]);
    else throw new Error(`unknown argument: ${rest[i]}`);
  }
  if (!['fetch', 'publish'].includes(opts.command)) throw new Error('usage: web-editor-artifact.mjs <fetch|publish> --base gs://bucket/prefix [--dir path]');
  if (!/^gs:\/\/[a-z0-9._-]+(\/[A-Za-z0-9._-]+)*$/.test(String(opts.base || ''))) throw new Error('--base must be a gs://bucket/prefix URI');
  return opts;
}

function main() {
  const opts = parseArgs(process.argv.slice(2));
  const version = webEditorArtifactVersion();
  const remote = `${opts.base.replace(/\/$/, '')}/${version}`;
  const dir = opts.dir || vendorReleaseDir;

  if (opts.command === 'publish') {
    const manifest = buildManifest(dir);
    const staging = fs.mkdtempSync(path.join(os.tmpdir(), 'web-editor-artifact-'));
    try {
      for (const name of listPublishableFiles(dir)) fs.copyFileSync(path.join(dir, name), path.join(staging, name));
      fs.writeFileSync(path.join(staging, MANIFEST_NAME), manifest);
      verifyDir(staging);
      gcloud(['storage', 'cp', '--no-clobber', path.join(staging, '*'), `${remote}/`]);
    } finally {
      fs.rmSync(staging, { recursive: true, force: true });
    }
    console.log(`Published web editor artifact ${version} -> ${remote}/`);
    return;
  }

  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
  gcloud(['storage', 'cp', `${remote}/*`, `${dir}/`]);
  const entries = verifyDir(dir);
  console.log(`Fetched and verified web editor artifact ${version} (${entries.size} files) -> ${path.relative(repoRoot, dir)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (error) {
    console.error(`[web-editor-artifact] ${error.message}`);
    process.exit(1);
  }
}
