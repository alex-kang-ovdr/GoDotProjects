#!/usr/bin/env node
/**
 * sync-data.mjs
 * Bundles games/isaku/ReverseDesign/verified_data/*.json into
 * games/isaku/Web/data/game-data.js (UMD: globalThis.ISAKU_DATA + module.exports).
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const gameRoot = resolve(__dirname, '..');
const verifiedDir = join(gameRoot, 'ReverseDesign', 'verified_data');
const outPath = join(gameRoot, 'Web', 'data', 'game-data.js');

const readJson = (file) => JSON.parse(readFileSync(join(verifiedDir, file), 'utf8'));

const charactersDoc = readJson('characters.json');
const roomsDoc = readJson('rooms.json');
const itemsDoc = readJson('items.json');
const puzzlesDoc = readJson('puzzles.json');
const incidentsDoc = readJson('incidents_and_endings.json');

const bundle = {
  schemaVersion: '1.0.0',
  gameId: 'isaku',
  generatedFrom: 'ReverseDesign/verified_data/*.json',
  title: charactersDoc.title,
  setting: charactersDoc.setting,
  startRoomId: roomsDoc.startRoomId,
  goalRoomId: roomsDoc.goalRoomId,
  floors: roomsDoc.floors,
  characters: charactersDoc.characters,
  rooms: roomsDoc.rooms,
  items: itemsDoc.items,
  puzzles: puzzlesDoc.puzzles,
  clockModel: incidentsDoc.clockModel,
  safetyAbstractionNotice: incidentsDoc.safetyAbstractionNotice,
  incidents: incidentsDoc.incidents,
  endings: incidentsDoc.endings,
};

const hotspotCount = bundle.rooms.reduce((acc, room) => acc + room.hotspots.length, 0);

const output = `// AUTO-GENERATED by Source/sync-data.mjs from ReverseDesign/verified_data/*.json
// Do not edit manually; re-run: node games/isaku/Source/sync-data.mjs
(function (root, factory) {
  const data = factory();
  if (typeof module === 'object' && module.exports) {
    module.exports = data;
  }
  root.ISAKU_DATA = data;
})(typeof globalThis !== 'undefined' ? globalThis : this, function () {
  return ${JSON.stringify(bundle, null, 2)};
});
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, output, 'utf8');

console.log(
  `[isaku:sync-data] Wrote Web/data/game-data.js — characters=${bundle.characters.length}, rooms=${bundle.rooms.length}, hotspots=${hotspotCount}, items=${bundle.items.length}, puzzles=${bundle.puzzles.length}, incidents=${bundle.incidents.length}, endings=${bundle.endings.length}`
);
