#!/usr/bin/env node
/**
 * YU-NO SSOT Data Bundler (ESM)
 * Bundles ReverseDesign/verified_data/*.json into Web/data/game-data.js
 * Exports globalThis.YUNO_DATA (browser file:// & HTTP) and module.exports (Node UMD).
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const gameRoot = resolve(__dirname, '..');
const verifiedDir = join(gameRoot, 'ReverseDesign', 'verified_data');
const outFile = join(gameRoot, 'Web', 'data', 'game-data.js');

function readJson(filename) {
  return JSON.parse(readFileSync(join(verifiedDir, filename), 'utf8'));
}

const charactersData = readJson('characters.json');
const locationsData = readJson('locations.json');
const routesData = readJson('routes_and_endings.json');
const itemsData = readJson('items_and_jewels.json');
const flagsData = readJson('flags_and_inheritance.json');
const admsData = readJson('adms_nodes.json');

const bundle = {
  schemaVersion: '1.0.0',
  gameId: 'yu-no',
  titleKo: charactersData.title_ko,
  titleJp: charactersData.title_jp,
  titleEn: charactersData.title_en,
  counts: {
    characters: charactersData.characters.length,
    locations: locationsData.locations.length,
    routes: routesData.routes.length,
    endings: routesData.endings.length,
    jewels: itemsData.jewels.length,
    items: itemsData.items.length,
    carriedItems: itemsData.items.filter((i) => i.carries_across_timelines).length,
    localItems: itemsData.items.filter((i) => !i.carries_across_timelines).length,
    globalFlags: flagsData.global_flags.length,
    localFlags: flagsData.local_flags.length,
    crossRouteTransfers: flagsData.cross_route_transfers.length,
    admsNodes: admsData.nodes.length,
  },
  characters: charactersData.characters,
  locations: locationsData.locations,
  recommendedPlayOrder: routesData.recommended_play_order,
  routes: routesData.routes,
  endings: routesData.endings,
  reflectorDevice: itemsData.reflector_device,
  jewels: itemsData.jewels,
  items: itemsData.items,
  statePartitionRules: flagsData.state_partition_rules,
  globalFlags: flagsData.global_flags,
  localFlags: flagsData.local_flags,
  crossRouteTransfers: flagsData.cross_route_transfers,
  rootNodeId: admsData.root_node_id,
  nodeTypeLegend: admsData.node_type_legend,
  nodes: admsData.nodes,
};

mkdirSync(dirname(outFile), { recursive: true });

const outputSource = `/* AUTO-GENERATED by Source/sync-data.mjs from ReverseDesign/verified_data/*.json — DO NOT EDIT DIRECTLY */
(function (root, factory) {
  var data = factory();
  if (typeof module === 'object' && module.exports) {
    module.exports = data;
  }
  if (root) {
    root.YUNO_DATA = data;
  }
}(typeof globalThis !== 'undefined' ? globalThis : (typeof window !== 'undefined' ? window : this), function () {
  return ${JSON.stringify(bundle, null, 2)};
}));
`;

writeFileSync(outFile, outputSource, 'utf8');

console.log(`Synced YU-NO verified_data -> ${outFile}`);
console.log(
  `  Characters: ${bundle.counts.characters} | Locations: ${bundle.counts.locations} | Nodes: ${bundle.counts.admsNodes}`
);
console.log(
  `  Routes: ${bundle.counts.routes} | Endings: ${bundle.counts.endings} | Jewels: ${bundle.counts.jewels} | Items: ${bundle.counts.items} (${bundle.counts.carriedItems} carried / ${bundle.counts.localItems} local)`
);
console.log(
  `  Flags: ${bundle.counts.globalFlags} global + ${bundle.counts.localFlags} local | Cross-route transfers: ${bundle.counts.crossRouteTransfers}`
);
