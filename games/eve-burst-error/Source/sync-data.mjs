#!/usr/bin/env node
/**
 * EVE burst error — Verified Data Bundler
 *
 * Reads ReverseDesign/verified_data/*.json (SSOT) and generates
 * Web/data/game-data.js with UMD-style globalThis.EVE_DATA + module.exports
 * so it works identically over file://, HTTP, and headless Node tests.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const gameRoot = path.resolve(__dirname, '..');
const verifiedDir = path.join(gameRoot, 'ReverseDesign', 'verified_data');
const outFile = path.join(gameRoot, 'Web', 'data', 'game-data.js');

function readJson(fileName) {
  const fullPath = path.join(verifiedDir, fileName);
  const raw = fs.readFileSync(fullPath, 'utf8');
  return JSON.parse(raw);
}

const charactersDoc = readJson('characters.json');
const locationsDoc = readJson('locations.json');
const timelineDoc = readJson('timeline_chapters.json');
const barriersDoc = readJson('sync_barriers.json');
const cluesDoc = readJson('clues_and_asymmetry.json');
const itemsEndingsDoc = readJson('items_and_endings.json');

const bundle = {
  schemaVersion: '1.0.0',
  gameId: 'eve-burst-error',
  sourceBaseline: charactersDoc.source_baseline || 'PC-98 (1995) / SEGA SATURN (1997) / EVE burst error R (2016)',
  calendarSpan: timelineDoc.calendar_span,
  characters: charactersDoc.characters,
  locations: locationsDoc.locations,
  scenes: timelineDoc.scenes,
  syncBarriers: barriersDoc.sync_barriers,
  clues: cluesDoc.clues,
  items: itemsEndingsDoc.items,
  endings: itemsEndingsDoc.endings_and_outcomes,
};

// Sanity assertions matching verified_data SSOT counts
const assertions = [
  ['characters', bundle.characters.length, 18],
  ['locations', bundle.locations.length, 14],
  ['scenes', bundle.scenes.length, 16],
  ['syncBarriers', bundle.syncBarriers.length, 8],
  ['clues', bundle.clues.length, 12],
  ['items', bundle.items.length, 12],
  ['endings', bundle.endings.length, 4],
];

for (const [label, actual, expected] of assertions) {
  if (actual !== expected) {
    throw new Error(`SSOT count mismatch for ${label}: expected ${expected}, got ${actual}`);
  }
}

fs.mkdirSync(path.dirname(outFile), { recursive: true });

const serialized = JSON.stringify(bundle, null, 2);
const output = `/* AUTO-GENERATED by Source/sync-data.mjs from ReverseDesign/verified_data/*.json — DO NOT EDIT MANUALLY */
(function (root, factory) {
  var data = factory();
  if (typeof module === 'object' && module && module.exports) {
    module.exports = data;
  }
  root.EVE_DATA = data;
})(typeof globalThis !== 'undefined' ? globalThis : typeof window !== 'undefined' ? window : this, function () {
  'use strict';
  return ${serialized};
});
`;

fs.writeFileSync(outFile, output, 'utf8');

console.log('=== EVE burst error Data Sync Complete ===');
console.log(`Output      : ${path.relative(gameRoot, outFile)}`);
console.log(`Characters  : ${bundle.characters.length}`);
console.log(`Locations   : ${bundle.locations.length}`);
console.log(`Scenes      : ${bundle.scenes.length}`);
console.log(`SyncBarriers: ${bundle.syncBarriers.length}`);
console.log(`Clues       : ${bundle.clues.length}`);
console.log(`Items       : ${bundle.items.length}`);
console.log(`Endings     : ${bundle.endings.length}`);
