#!/usr/bin/env bash
set -euo pipefail

# One-command Free Apple ID ($0 Personal Team) USB iPhone / Simulator setup script (macOS).
# Prepares Godot 4.7.2 XCFramework, 7KB bootstrap data.pck, gitignored LocalFree.xcconfig,
# runs PlayHubCore swift test, generates PlayHub.xcodeproj via XcodeGen, and either
# installs directly to a USB-connected iPhone or opens Xcode on scheme PlayHubAppFree.
#
# Usage:
#   ./tools/ios/setup-free-usb.sh [--slug myname] [--team PERSONAL_TEAM_ID] [--hub-url https://xxx.trycloudflare.com] [--install] [--no-open]

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
IOS_DIR="${REPO_ROOT}/ios"

SLUG=""
TEAM_ID=""
HUB_URL=""
DO_INSTALL="0"
OPEN_XCODE="1"
SKIP_TESTS="0"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --slug) SLUG="$2"; shift 2 ;;
    --team) TEAM_ID="$2"; shift 2 ;;
    --hub-url) HUB_URL="$2"; shift 2 ;;
    --install) DO_INSTALL="1"; OPEN_XCODE="0"; shift ;;
    --no-open) OPEN_XCODE="0"; shift ;;
    --skip-tests) SKIP_TESTS="1"; shift ;;
    *) echo "Unknown arg: $1" >&2; exit 2 ;;
  esac
done

if [[ "$(uname -s)" != "Darwin" ]]; then
  echo "ERROR: This script must run on macOS with Xcode installed." >&2
  exit 1
fi

for cmd in xcodebuild node; do
  if ! command -v "${cmd}" >/dev/null 2>&1; then
    echo "ERROR: Missing required tool '${cmd}'." >&2
    exit 1
  fi
done

if ! command -v xcodegen >/dev/null 2>&1; then
  echo "ERROR: xcodegen is required (install via: brew install xcodegen)" >&2
  exit 1
fi

if [[ -z "${SLUG}" ]]; then
  RAW_USER="$(id -un | tr '[:upper:]' '[:lower:]' | tr -cd 'a-z0-9' | cut -c1-12)"
  SLUG="hub-ios-${RAW_USER:-free}"
fi

BUNDLE_ID="$(node -e '
  import("./tools/ios/verify-ipa.mjs").then(m => {
    console.log(m.expectedBundleId(process.argv[1], "debug"));
  }).catch(err => { console.error(err.message); process.exit(1); });
' "${SLUG}")"

echo "=== Play Hub iOS Free Apple ID ($0) USB Setup ==="
echo "Bundle ID : ${BUNDLE_ID}"
echo "Team ID   : ${TEAM_ID:-(Select Personal Team in Xcode Signing & Capabilities)}"
echo "Hub URL   : ${HUB_URL:-http://127.0.0.1:18130}"

# 1. Extract and SHA-256 verify locked Godot 4.7.2 release XCFramework
"${SCRIPT_DIR}/extract-godot-xcframework.sh"

# 2. Pack 7KB minimal bootstrap data.pck (0 starter games) without requiring Godot Editor
node "${SCRIPT_DIR}/pack-bootstrap.mjs" "${IOS_DIR}/App/Resources/Bootstrap/data.pck"

# 3. Write gitignored LocalFree.xcconfig (escape // as /$()/ for xcconfig comment parser)
LOCAL_CFG="${IOS_DIR}/Config/LocalFree.xcconfig"
{
  echo "// Auto-generated by tools/ios/setup-free-usb.sh (gitignored)"
  echo "PRODUCT_BUNDLE_IDENTIFIER = ${BUNDLE_ID}"
  if [[ -n "${TEAM_ID}" ]]; then
    echo "DEVELOPMENT_TEAM = ${TEAM_ID}"
  fi
  if [[ -n "${HUB_URL}" ]]; then
    ESCAPED_URL="${HUB_URL//\/\//\/\$()\/}"
    echo "PLAYHUB_DEFAULT_HUB_URL = ${ESCAPED_URL}"
  fi
} > "${LOCAL_CFG}"
echo "Wrote ${LOCAL_CFG}"

# 4. Run PlayHubCore pure Swift unit tests
if [[ "${SKIP_TESTS}" != "1" ]]; then
  echo "Running PlayHubCore swift test..."
  (cd "${IOS_DIR}/Packages/PlayHubCore" && swift test)
fi

# 5. Generate Xcode project
(cd "${IOS_DIR}" && xcodegen generate --spec project.yml)

# 6. List connected USB iPhones
echo "=== Connected iOS Devices ==="
if xcrun devicectl list devices >/dev/null 2>&1; then
  xcrun devicectl list devices || true
else
  xcrun xctrace list devices || true
fi

if [[ "${DO_INSTALL}" == "1" ]]; then
  if [[ -z "${TEAM_ID}" ]]; then
    echo "ERROR: --install requires --team <PERSONAL_TEAM_ID> (or omit --install to open Xcode and press Cmd+R)." >&2
    exit 2
  fi
  DEVICE_ID="$(xcrun xctrace list devices 2>/dev/null | grep -E 'iPhone|iPad' | grep -v 'Simulator' | head -n 1 | sed -E 's/.*\(([0-9A-Fa-f-]+)\)$/\1/' || true)"
  if [[ -z "${DEVICE_ID}" ]]; then
    echo "ERROR: No USB-connected physical iPhone/iPad detected. Connect via USB, unlock, and enable Developer Mode." >&2
    exit 1
  fi
  echo "Building & installing DebugFree (${BUNDLE_ID}) to USB device ${DEVICE_ID}..."
  DERIVED="${IOS_DIR}/build/free-usb-derived"
  xcodebuild build \
    -project "${IOS_DIR}/PlayHub.xcodeproj" \
    -scheme "PlayHubAppFree" \
    -configuration "DebugFree" \
    -destination "id=${DEVICE_ID}" \
    -derivedDataPath "${DERIVED}" \
    -allowProvisioningUpdates
  APP_BUNDLE="${DERIVED}/Build/Products/DebugFree-iphoneos/PlayHubApp.app"
  xcrun devicectl device install app --device "${DEVICE_ID}" "${APP_BUNDLE}"
  echo "SUCCESS: Installed on USB iPhone (${DEVICE_ID}). On first launch, trust the Personal Team in Settings -> General -> VPN & Device Management."
elif [[ "${OPEN_XCODE}" == "1" ]]; then
  echo "Opening PlayHub.xcodeproj in Xcode..."
  echo "Next steps in Xcode: Select scheme 'PlayHubAppFree' -> Signing & Capabilities -> select your free Personal Team -> pick your USB iPhone -> Cmd+R"
  open "${IOS_DIR}/PlayHub.xcodeproj"
fi
