function generateSpriteFramesTres(animations) {
  // animations: [{ name, fps, loop, spriteIndices: number[] }]
  const uniqueIndices = [...new Set(animations.flatMap((a) => a.spriteIndices))].sort((a, b) => a - b);
  const idByIndex = new Map();
  let extLines = [];
  uniqueIndices.forEach((idx, i) => {
    const id = String(i + 1);
    idByIndex.set(idx, id);
    const padded = String(idx).padStart(2, '0');
    extLines.push(`[ext_resource type="Texture2D" path="res://resources/atlas/sprite_${padded}.tres" id="${id}"]`);
  });

  const animBlocks = animations.map((a) => {
    const frames = a.spriteIndices
      .map((idx) => `{\n"duration": 1.0,\n"texture": ExtResource("${idByIndex.get(idx)}")\n}`)
      .join(', ');
    return `{\n"frames": [${frames}],\n"loop": ${a.loop ? 'true' : 'false'},\n"name": &"${a.name}",\n"speed": ${a.fps.toFixed(1)}\n}`;
  });

  return `[gd_resource type="SpriteFrames" load_steps=${uniqueIndices.length + 1} format=3]

${extLines.join('\n')}

[resource]
animations = [${animBlocks.join(', ')}]
`;
}

