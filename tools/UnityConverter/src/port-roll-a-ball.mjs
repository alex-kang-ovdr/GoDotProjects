function writeText(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content.replace(/\r\n/g, '\n'), 'utf8');
}

function walkFiles(dir, skip = new Set()) {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (skip.has(e.name)) continue;
    if (e.name.endsWith('.import') || e.name.endsWith('.uid')) continue;
    const full = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...walkFiles(full, skip));
    else out.push(full);
  }
  return out;
}

export function parseRollABallScene(unityScenePath) {
  const txt = fs.readFileSync(unityScenePath, 'utf8');
  const docs = txt.split(/^--- !u!/m).slice(1);
  const goNames = {};
  const objects = [];

  for (const d of docs) {
    const m = d.match(/^(\d+) &(\d+)/);
    if (!m) continue;
    const [, typeId, fileId] = m;
    if (typeId === '1') {
      const nm = d.match(/m_Name:\s*(.+)/);
      if (nm) goNames[fileId] = nm[1].trim();
    } else if (typeId === '4') {
      const go = d.match(/m_GameObject:\s*\{fileID:\s*(\d+)\}/)?.[1];
      const pos = d.match(/m_LocalPosition:\s*\{x:\s*([\d.-]+),\s*y:\s*([\d.-]+),\s*z:\s*([\d.-]+)\}/);
      const scale = d.match(/m_LocalScale:\s*\{x:\s*([\d.-]+),\s*y:\s*([\d.-]+),\s*z:\s*([\d.-]+)\}/);
      if (go && pos) {
        objects.push({
          goId: go,
          pos: [Number(pos[1]), Number(pos[2]), Number(pos[3])],
          scale: scale ? [Number(scale[1]), Number(scale[2]), Number(scale[3])] : [1, 1, 1],
        });
      }
    }
  }

  const pickups = [];
  const walls = [];
  let cameraPos = [0, 10, -10];
  let playerPos = [0, 0.5, 0];

  for (const o of objects) {
    const name = goNames[o.goId] || '';
    if (name === 'PickUp') {
      // Unity 3D LH (x, y, z) -> Godot 3D RH (x, y, -z)
      pickups.push({
        unityPos: o.pos,
        godotPos: [Number(o.pos[0].toFixed(3)), Number(o.pos[1].toFixed(3)), Number((-o.pos[2]).toFixed(3))],
      });
    } else if (name.endsWith('Wall')) {
      walls.push({
        name,
        godotPos: [Number(o.pos[0].toFixed(3)), Number((o.pos[1] + 0.5).toFixed(3)), Number((-o.pos[2]).toFixed(3))],
        size: [Number(o.scale[0].toFixed(3)), Number(o.scale[1].toFixed(3)), Number(o.scale[2].toFixed(3))],
      });
    } else if (name === 'Main Camera') {
      cameraPos = [o.pos[0], o.pos[1], -o.pos[2]];
    } else if (name === 'Player') {
      playerPos = [o.pos[0], o.pos[1], -o.pos[2]];
    }
  }

  return { pickups, walls, cameraPos, playerPos };
}

