function writeText(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content.replace(/\r\n/g, '\n'), 'utf8');
}

function walkFiles(dir, skip = new Set()) {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (skip.has(e.name)) continue;
    if (e.name.endsWith('.import') || e.name.endsWith('.uid')) continue;
    const full = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...walkFiles(full, skip));
    else out.push(full);
  }
  return out;
}

export function convertTiffDirectoryToPng(srcDir, dstDir) {
  fs.mkdirSync(dstDir, { recursive: true });
  const py = `
import os, sys, json
from PIL import Image
src, dst = sys.argv[1], sys.argv[2]
converted = []
for fn in sorted(os.listdir(src)):
    if not fn.lower().endswith('.tif'):
        continue
    in_p = os.path.join(src, fn)
    out_fn = os.path.splitext(fn)[0] + '.png'
    out_p = os.path.join(dst, out_fn)
    with Image.open(in_p) as im:
        im.convert('RGBA').save(out_p)
        converted.append({
            'input': fn,
            'output': out_fn,
            'width': im.width,
            'height': im.height,
            'inBytes': os.path.getsize(in_p),
            'outBytes': os.path.getsize(out_p),
        })
print(json.dumps(converted))
`;
  const raw = execFileSync('python', ['-c', py, srcDir, dstDir], { encoding: 'utf8' });
  return JSON.parse(raw.trim());
}

