/**
 * Generate a complete, playable Godot 4.7.2 project from Unified Game IR v0.1.
 */
export function generateGodotProjectFromIR(ir, outDir, options = {}) {
  const absOut = path.resolve(outDir);
  fs.mkdirSync(path.join(absOut, "scenes"), { recursive: true });
  fs.mkdirSync(path.join(absOut, "scripts"), { recursive: true });
  fs.mkdirSync(path.join(absOut, "tests"), { recursive: true });

  copyCompatAddon(absOut);

  const compiledScripts = {};
  const allSourceMaps = [];
  const compileDiagnostics = [];

  for (const graph of ir.logic || []) {
    const compiled = compileBlueprintToGDScript(graph, options);
    compiledScripts[graph.id] = compiled;
    fs.writeFileSync(path.join(absOut, "scripts", compiled.scriptName), compiled.code, "utf8");
    allSourceMaps.push(...compiled.sourceMap);
    compileDiagnostics.push(...compiled.diagnostics);
  }

  fs.writeFileSync(path.join(absOut, "scripts", "hud_overlay.gd"), generateHudScript(), "utf8");
  fs.writeFileSync(path.join(absOut, "project.godot"), generateProjectGodot(ir), "utf8");
  fs.writeFileSync(path.join(absOut, "scenes", "main.tscn"), generateMainTscn(ir, compiledScripts), "utf8");
  fs.writeFileSync(path.join(absOut, "tests", "verify_and_trace.gd"), generateVerifyAndTraceScript(), "utf8");
  fs.writeFileSync(path.join(absOut, "tests", "verify_and_trace.tscn"), generateVerifyTscn(), "utf8");

  return {
    outputDir: absOut,
    generatedFiles: [
      "project.godot",
      "scenes/main.tscn",
      "scripts/hud_overlay.gd",
      ...Object.values(compiledScripts).map((c) => `scripts/${c.scriptName}`),
      "addons/playforge_unreal_compat/plugin.cfg",
      "addons/playforge_unreal_compat/plugin.gd",
      "addons/playforge_unreal_compat/unreal_compat.gd",
      "addons/playforge_unreal_compat/ue_character_movement.gd",
      "tests/verify_and_trace.gd",
      "tests/verify_and_trace.tscn"
    ],
    sourceMap: allSourceMaps,
    diagnostics: compileDiagnostics
  };
}
