'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require('@playwright/test');
const { createServer } = require('../server.cjs');
const root = path.resolve(__dirname, '..');
const out = path.join(root, 'Saved/Tests/web-runtime');
fs.mkdirSync(out, {recursive:true});
const server = createServer({workspace:path.join(out,'workspace'), buildDirectory:path.join(out,'builds')});
let browser;
const delay = ms => new Promise(resolve => setTimeout(resolve,ms));
(async () => {
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const origin='http://127.0.0.1:'+server.address().port;
  const doc=await (await fetch(origin+'/api/project')).json();
  let response=await fetch(origin+'/api/builds',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({target:'web',revision:doc.revision})});
  assert.equal(response.status,202);
  let {build}=await response.json();
  const deadline=Date.now()+180000;
  while(['queued','running'].includes(build.status) && Date.now()<deadline){await delay(500);build=(await(await fetch(origin+'/api/builds/'+build.id)).json()).build;}
  fs.writeFileSync(path.join(out,'build.json'),JSON.stringify(build,null,2));
  assert.equal(build.status,'succeeded',build.error);
  console.log('PASS actual Godot Web export',build.id);
  browser=await chromium.launch({channel:'chrome',headless:!process.argv.includes('--official'),args:['--enable-unsafe-swiftshader']});
  const page=await browser.newPage({viewport:{width:1100,height:850}});
  const errors=[]; const logs=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',msg=>{logs.push(msg.type()+': '+msg.text());if(/SCRIPT ERROR:|ERROR:/.test(msg.text()))errors.push(msg.text());});
  await page.goto(origin+build.previewUrl);
  await page.waitForFunction(()=>!!window.PlayForgeRuntimeState,{},{timeout:60000});
  const state=()=>page.evaluate(()=>JSON.parse(window.PlayForgeRuntimeState));
  await page.locator('#canvas').focus();
  await page.keyboard.press('KeyR');
  await page.waitForFunction(()=>JSON.parse(window.PlayForgeRuntimeState).state==='ready');
  assert.equal((await state()).state,'ready');
  await page.locator('#canvas').click({position:{x:300,y:300}});
  await page.waitForFunction(()=>JSON.parse(window.PlayForgeRuntimeState).state==='playing');
  await page.keyboard.press('KeyP');
  await page.waitForFunction(()=>JSON.parse(window.PlayForgeRuntimeState).state==='paused');
  const paused=await state(); await delay(180); assert.deepEqual(await state(),paused);
  await page.screenshot({path:path.join(out,'web-game.png')});
  await page.keyboard.press('KeyR');
  await page.waitForFunction(()=>JSON.parse(window.PlayForgeRuntimeState).state==='ready');
  assert.equal(errors.length,0,errors.join('\n'));
  fs.writeFileSync(path.join(out,'runtime.json'),JSON.stringify({passed:true,engine:'Godot Web WASM',build:build.id,revision:build.revision,paused},null,2));
  fs.writeFileSync(path.join(out,'browser.log'),logs.join('\n'));
  console.log('PASS browser WASM load, input, pause freeze, restart');
  response=await fetch(origin+build.downloadUrl); assert.equal(response.status,200); await response.arrayBuffer();
  if (!process.argv.includes('--official')) return;
  const zip=Buffer.from(await(await fetch(origin+'/api/export/godot-project.zip')).arrayBuffer());
  fs.writeFileSync(path.join(out,'editor-project.zip'),zip);
  await page.goto(origin+'/OfficialGodot/vendor/godot.editor.html');
  const dismiss=page.locator('#welcome-modal-dismiss'); if(await dismiss.isVisible()) await dismiss.click();
  assert.equal(await page.evaluate(()=>crossOriginIsolated),true);
  await page.locator('#zip-file').setInputFiles({name:'PlayForge.zip',mimeType:'application/zip',buffer:zip});
  await page.locator('#startButton').click();
  await page.waitForFunction(()=>!document.getElementById('btn-tab-editor').disabled,{},{timeout:90000});
  await delay(2000);
  await page.screenshot({path:path.join(out,'official-editor.png')});
  await page.keyboard.press('Enter');
  const editorDeadline = Date.now() + 60000;
  while (!logs.some(line=>line.includes('PLAYFORGE_EDITOR_READY')) && Date.now()<editorDeadline) await delay(1000);
  await delay(2000); // Let the editor draw the dock after the ready marker.
  await page.screenshot({path:path.join(out,'official-project.png')});
  fs.writeFileSync(path.join(out,'official-browser.log'),logs.join('\n'));
  fs.writeFileSync(path.join(out,'official-result.json'),JSON.stringify({pluginReady:logs.some(line=>line.includes('PLAYFORGE_EDITOR_READY')),errors},null,2));
  assert.ok(logs.some(line=>line.includes('PLAYFORGE_EDITOR_READY')), 'Official editor plugin did not become ready; inspect official-browser.log and official-project.png');
  assert.equal(errors.length,0,errors.join('\n'));
  console.log('PASS self-hosted official editor start + preloaded ZIP; inspect project screenshot');
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{if(browser)await browser.close();server.shutdown();server.closeAllConnections();});
