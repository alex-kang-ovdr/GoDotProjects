'use strict';
const test = require('node:test'), assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const { chromium } = require('@playwright/test');
const { createServer } = require('../server.cjs');

test('Fortress workspace routes same-room clients, ignores stale relays and refreshes observers between worlds', { timeout: 60000 }, async t => {
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'fortress-workspace-'));
  const server = createServer({workspace:path.join(temporary,'workspace'),platformWorkspace:path.join(temporary,'platform'),buildDirectory:path.join(temporary,'builds')});
  await new Promise(resolve => server.listen(0,'127.0.0.1',resolve));
  const base = 'http://127.0.0.1:' + server.address().port;
  const browser = await chromium.launch({channel:'chrome',headless:true});
  t.after(async () => { await browser.close(); await new Promise(resolve => { server.once('close',resolve); server.shutdown(); }); fs.rmSync(temporary,{recursive:true,force:true}); });
  const page = await browser.newPage();
  const errors = []; page.on('pageerror',error => errors.push(error.message));
  let observerLoads = 0;
  await page.route('**/api/builds/aaaaaaaaaaaaaaaa/files/index.html*', async route => {
    observerLoads++;
    await route.fulfill({contentType:'text/html',headers:{'Cross-Origin-Embedder-Policy':'require-corp','Cross-Origin-Opener-Policy':'same-origin','Cross-Origin-Resource-Policy':'same-origin'},body:'<!doctype html><script>parent.postMessage({source:"playforge-fortress-game",type:"ready"},location.origin)</script>'});
  });
  await page.goto(base + '/OfficialGodot/multiplayer.html?template=fortress-war&project=0123456789abcdef01234567');
  await page.waitForFunction(() => window.PlayForgeMultiplayer?.clients.length === 1);
  const first = page.frames().find(frame => frame.url().includes('fortress-war-lobby.html'));
  assert.ok(first, 'Fortress projects must select the Fortress lobby');
  const makeMessage = (roomId,serverTime,hp) => ({source:'playforge-fortress-client',type:'state',playerId:'p1',roomId,projectId:'0123456789abcdef01234567',buildId:'a'.repeat(16),revision:1,previewUrl:'/api/builds/'+'a'.repeat(16)+'/files/index.html',state:{roomId,phase:'playing',serverTime,players:[{id:'p1',team:0,spectator:false}],game:{tanks:[{uid:'t0_0',name:'캐터펄트',team:0,x:200,y:400,hp}]},logs:[]}});
  await first.evaluate(message => parent.postMessage(message,location.origin), makeMessage('111111111111',200,960));
  await page.waitForFunction(() => window.PlayForgeMultiplayer.snapshot.serverTime === 200);
  await first.evaluate(message => parent.postMessage(message,location.origin), makeMessage('111111111111',100,500));
  await page.waitForTimeout(100);
  assert.equal(await page.evaluate(() => window.PlayForgeMultiplayer.snapshot.game.tanks[0].hp),960,'A stale relay cannot roll back the observer');
  await page.locator('#add-client').click();
  const second = page.locator('.client-frame[data-client-id="client-2"]');
  await second.waitFor();
  assert.match(await second.getAttribute('src'), /fortress-war-lobby\.html.*room=111111111111/);
  await page.locator('#server-tab').click();
  await page.waitForFunction(() => document.querySelector('#server-wait').hidden);
  const firstLoads = observerLoads;
  await page.locator('#new-world').click();
  const third = page.locator('.client-frame[data-client-id="client-3"]');
  await third.waitFor();
  const thirdSource = await third.getAttribute('src');
  assert.match(thirdSource,/fortress-war-lobby\.html/); assert.ok(!thirdSource.includes('room='));
  await page.waitForFunction(() => document.querySelector('.client-frame[data-client-id="client-3"]').contentWindow?.document.querySelector('#join-form'));
  const thirdFrame = await (await third.elementHandle()).contentFrame();
  await thirdFrame.evaluate(message => parent.postMessage(message,location.origin), makeMessage('222222222222',300,880));
  await page.locator('#server-tab').click();
  await page.waitForFunction(() => window.PlayForgeMultiplayer.snapshot.roomId === '222222222222' && document.querySelector('#server-wait').hidden);
  assert.ok(observerLoads > firstLoads,'Another world with the same build must create a fresh observer');
  assert.deepEqual(errors,[]);
});
